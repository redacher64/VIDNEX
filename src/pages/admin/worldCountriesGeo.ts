/**
 * Simplified World Countries GeoJSON embedded directly in the bundle.
 * Zero external network calls, zero heavy mapping dependencies.
 * Coordinates are [longitude, latitude] rings in WGS84 projected onto a 1000x500 SVG viewBox.
 */

export interface CountryGeoFeature {
  type: 'Feature';
  id: string; // ISO 3166-1 alpha-2
  properties: {
    code: string;
    nameFr: string;
  };
  geometry: {
    type: 'MultiPolygon';
    coordinates: Array<Array<Array<[number, number]>>>;
  };
}

export interface WorldCountriesGeoJSON {
  type: 'FeatureCollection';
  features: CountryGeoFeature[];
}

export interface ProjectedCountryShape {
  code: string;
  nameFr: string;
  d: string;
  centroidX: number;
  centroidY: number;
}

const MIN_LAT = -58;
const MAX_LAT = 82;
const LAT_SPAN = MAX_LAT - MIN_LAT; // 140 degrees

function round1(n: number): number {
  return Math.round(n * 10) / 10;
}

export function projectGeoLonLat(lon: number, lat: number): [number, number] {
  const clampedLon = Math.max(-180, Math.min(180, lon));
  const clampedLat = Math.max(MIN_LAT, Math.min(MAX_LAT, lat));
  const x = round1(((clampedLon + 180) / 360) * 1000);
  const y = round1(((MAX_LAT - clampedLat) / LAT_SPAN) * 500);
  return [x, y];
}

export function geoMultiPolygonToSvgPath(
  multiPoly: Array<Array<Array<[number, number]>>>
): string {
  const parts: string[] = [];
  for (const poly of multiPoly) {
    for (const ring of poly) {
      if (ring.length < 3) continue;
      const cmds = ring.map(([lon, lat], idx) => {
        const [x, y] = projectGeoLonLat(lon, lat);
        return `${idx === 0 ? 'M' : 'L'}${x},${y}`;
      });
      parts.push(`${cmds.join(' ')} Z`);
    }
  }
  return parts.join(' ');
}

function computeCentroid(
  multiPoly: Array<Array<Array<[number, number]>>>
): { centroidX: number; centroidY: number } {
  const mainRing = multiPoly[0]?.[0];
  if (!mainRing || mainRing.length === 0) {
    return { centroidX: 500, centroidY: 250 };
  }
  let sumX = 0;
  let sumY = 0;
  for (const [lon, lat] of mainRing) {
    const [x, y] = projectGeoLonLat(lon, lat);
    sumX += x;
    sumY += y;
  }
  return {
    centroidX: round1(sumX / mainRing.length),
    centroidY: round1(sumY / mainRing.length),
  };
}

