export function getCountryNameFr(code: string): string {
  const upper = (code || 'XX').trim().toUpperCase();
  return COUNTRY_NAME_MAP[upper] || upper;
}

export function getCountryFlag(code: string): string {
  const upper = (code || '').trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper) || upper === 'XX') return '🌐';
  return String.fromCodePoint(
    upper.charCodeAt(0) + 127397,
    upper.charCodeAt(1) + 127397
  );
}
